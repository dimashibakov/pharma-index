-- Drug Litigation Index — reference schema
-- Supabase project: pbzkpsrmsvapyjbdatdr (Pharma Litigation Index)
-- Public-read only: every table has RLS on with an anon/authenticated SELECT policy.
-- The front-end reads these tables directly via PostgREST with the publishable (anon) key.

create table if not exists drugs (
  id                   bigint generated by default as identity primary key,
  slug                 text not null unique,
  name                 text not null,
  short_name           text,
  brands               text,
  drug_class           text,
  drug_type            text,              -- grouping used by Browse/Explore facets
  manufacturer         text,              -- free-text legacy field
  manufacturer_primary text,              -- fallback display maker
  first_approval       text,
  rxnorm_cui           text,
  status               text,              -- active | winding | closed | none
  signal_index         integer,          -- 0..100 composite
  band                 text,              -- Low | Moderate | Elevated | High
  confidence           text,
  fda_summary          text,
  boxed_warning        text,
  eu_status            text,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now()
);

-- Weighted composite components (4 per drug).
-- position 1..4 = Regulatory 30% / Litigation volume 25% / AE severity 25% / Court outcomes 20%.
create table if not exists signal_components (
  id           bigint generated by default as identity primary key,
  drug_id      bigint not null references drugs(id) on delete cascade,
  position     integer,
  name         text not null,
  weight       numeric,
  score        integer,                   -- 0..100; null => pending (outcomes), weight redistributed
  value        text,                      -- human-readable value shown on the bar
  is_estimated boolean not null default false,
  description  text
);

-- Manufacturer as an entity, with succession (originator/current/former) modelled separately.
create table if not exists manufacturers (
  id           bigint generated by default as identity primary key,
  slug         text not null unique,
  name         text not null,
  status       text not null,             -- active | defunct | ...
  org_type     text,                      -- for-profit | public-benefit | family | ...
  succeeded_by bigint references manufacturers(id),
  note         text,
  created_at   timestamptz not null default now()
);

-- Time-bounded role of a manufacturer on a drug. The front-end derives the
-- displayed maker from role='current_manufacturer' (e.g. OxyContin -> Knoa Pharma),
-- and lists role in ('former_manufacturer','originator') as succession (e.g. Purdue).
create table if not exists drug_manufacturers (
  id              bigint generated by default as identity primary key,
  drug_id         bigint not null references drugs(id) on delete cascade,
  manufacturer_id bigint not null references manufacturers(id),
  role            text not null,          -- current_manufacturer | former_manufacturer | originator | marketer | co_defendant
  valid_from      text,
  valid_to        text
);

create table if not exists litigation (
  id                bigint generated by default as identity primary key,
  drug_id           bigint not null references drugs(id) on delete cascade,
  docket            text,                 -- e.g. "MDL 3094"
  title             text,
  court             text,
  judge             text,
  consolidated      text,
  injuries          text,
  pending           text,
  plaintiff_verdicts text,
  defense_dismissed text,
  settlements       text,
  as_of             text,
  status            text,
  is_excluded       boolean not null default false,  -- excluded from the volume signal
  note              text
);

-- Named defendants on a case (may be a manufacturer entity or a free-text name,
-- e.g. the Sackler family alongside Purdue).
create table if not exists litigation_defendants (
  id              bigint generated by default as identity primary key,
  litigation_id   bigint not null references litigation(id) on delete cascade,
  manufacturer_id bigint references manufacturers(id),
  defendant_name  text,
  note            text
);

create table if not exists data_sources (
  id          bigint generated by default as identity primary key,
  name        text not null,
  category    text not null,              -- legal | medical
  access      text not null,              -- available | limited | paid
  coverage    text,
  freshness   text,
  update_tier text,                       -- A | B | C (pull cadence) — see ADR-002
  url         text,
  notes       text,
  created_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Row Level Security: public read on every table (consumer product, no writes).
-- ---------------------------------------------------------------------------
alter table drugs                 enable row level security;
alter table signal_components     enable row level security;
alter table manufacturers         enable row level security;
alter table drug_manufacturers    enable row level security;
alter table litigation            enable row level security;
alter table litigation_defendants enable row level security;
alter table data_sources          enable row level security;

create policy "anon read drugs"                 on drugs                 for select to anon, authenticated using (true);
create policy "anon read signal_components"      on signal_components     for select to anon, authenticated using (true);
create policy "anon read manufacturers"          on manufacturers         for select to anon, authenticated using (true);
create policy "anon read drug_manufacturers"     on drug_manufacturers    for select to anon, authenticated using (true);
create policy "anon read litigation"             on litigation            for select to anon, authenticated using (true);
create policy "anon read litigation_defendants"  on litigation_defendants for select to anon, authenticated using (true);
create policy "anon read data_sources"           on data_sources          for select to anon, authenticated using (true);
